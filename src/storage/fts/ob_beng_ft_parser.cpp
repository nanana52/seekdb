int ObBEngFTParser::get_next_token(
    const char *&word,
    int64_t &word_len,
    int64_t &char_len,
    int64_t &word_freq)
{
  int ret = OB_SUCCESS;
  ObDatum token;
  int64_t token_freq = 0;
  char *buf = nullptr;
  word = nullptr;
  word_len = 0;
  char_len = 0;
  word_freq = 0;
  if (OB_UNLIKELY(!is_inited_)) {
    ret = OB_NOT_INIT;
  } else if (ascii_fast_) {
    const ObCharsetInfo *cs=analysis_ctx_.cs_;
    const auto delimiter=[cs](char c) {
      return ob_isspace(cs,c)||ob_iscntrl(cs,c)||ob_ispunct(cs,c);
    };
    while(ascii_pos_<doc_.len_ && delimiter(doc_.ptr_[ascii_pos_]))++ascii_pos_;
    int64_t first=ascii_pos_;
    while(ascii_pos_<doc_.len_ && !delimiter(doc_.ptr_[ascii_pos_]))++ascii_pos_;
    int64_t last=ascii_pos_;
    while(first<last && !ob_isalnum(cs,doc_.ptr_[first]))++first;
    while(last>first && !ob_isalnum(cs,doc_.ptr_[last-1]))--last;
    if(first==last) {
      ret=OB_ITER_END;
    } else {
      // The normalized document is owned by the caller's allocator. Token
      // slices remain valid after this iterator is freed, as in the old path.
      word=doc_.ptr_+first;
      word_len=last-first;char_len=word_len;word_freq=1;
    }
  } else if (OB_ISNULL(token_stream_)) {
    ret = OB_ERR_UNEXPECTED;
  } else if (OB_FAIL(token_stream_->get_next(token, token_freq))) {
    if (OB_ITER_END != ret) {
    }
  } else if (OB_ISNULL(token.ptr_) || OB_UNLIKELY(0 >= token.len_ || 0 >= token_freq)) {
    ret = OB_INVALID_ARGUMENT;
  } else if (OB_ISNULL(buf = static_cast<char *>(allocator_.alloc(token.len_)))) {
    ret = OB_ALLOCATE_MEMORY_FAILED;
  } else {
    MEMCPY(buf, token.ptr_, token.len_);
    word = buf;
    word_len = token.len_;
    char_len = token.len_;
    word_freq = token_freq;
    LOG_DEBUG("succeed to add word", K(ObString(word_len, word)), K(word_freq));
  }
  return ret;
}

int ObBEngFTParser::init(ObFTParserParam *param)
{
  int ret = OB_SUCCESS;
  if (OB_UNLIKELY(is_inited_)) {
    ret = OB_INIT_TWICE;
  } else if (OB_ISNULL(param) || OB_UNLIKELY(!param->is_valid())) {
    ret = OB_INVALID_ARGUMENT;
  } else if (OB_UNLIKELY(UINT32_MAX < param->ft_length_)) {
    ret = OB_NOT_SUPPORTED;
  } else {
    doc_.set_string(param->fulltext_, param->ft_length_);
    analysis_ctx_.cs_ = param->cs_;
    analysis_ctx_.filter_stopword_ = false;
    analysis_ctx_.need_grouping_ = false;
    ascii_pos_=0;
    ascii_fast_=param->cs_->name!=nullptr &&
        (0==strcmp(param->cs_->name,"utf8mb4_bin") ||
         0==strcmp(param->cs_->name,"utf8mb4_general_ci") ||
         0==strcmp(param->cs_->name,"utf8mb4_unicode_ci"));
    for(int64_t i=0;ascii_fast_&&i<doc_.len_;++i) {
      ascii_fast_=static_cast<unsigned char>(doc_.ptr_[i])<128;
    }
    if(ascii_fast_) {
      char *normalized=static_cast<char *>(allocator_.alloc(doc_.len_));
      if(OB_ISNULL(normalized)) {
        ret=OB_ALLOCATE_MEMORY_FAILED;
      } else {
        for(int64_t i=0;i<doc_.len_;++i) {
          const char value=doc_.ptr_[i];
          normalized[i]=value>='A'&&value<='Z'?value-'A'+'a':value;
        }
        doc_.set_string(normalized,doc_.len_);
        is_inited_=true;
      }
    } else if (OB_FAIL(english_analyzer_.init(analysis_ctx_, *param->allocator_))) {
    } else if (OB_FAIL(segment(doc_, token_stream_))) {
    } else if (OB_ISNULL(token_stream_)) {
      ret = OB_ERR_UNEXPECTED;
    } else {
      is_inited_ = true;
    }
  }
  if (OB_FAIL(ret) && OB_UNLIKELY(!is_inited_)) {
    reset();
  }
  return ret;
}

int ObBEngFTParser::segment(
    const common::ObDatum &doc,
    share::ObITokenStream *&token_stream)
{
  int ret = OB_SUCCESS;
  if (OB_ISNULL(doc.ptr_) || OB_UNLIKELY(0 >= doc.len_)) {
    ret = OB_INVALID_ARGUMENT;
  } else if (OB_UNLIKELY(UINT32_MAX < doc.len_)) {
    ret = OB_NOT_SUPPORTED;
  } else if (OB_FAIL(english_analyzer_.analyze(doc, token_stream))) {
  }
  return ret;
}

void ObBEngFTParser::reset()
{
  analysis_ctx_.reset();
  english_analyzer_.reset();
  doc_.reset();
  token_stream_ = nullptr;
  is_inited_ = false;
  ascii_fast_=false;
  ascii_pos_=0;
}

ObBasicEnglishFTParserDesc::ObBasicEnglishFTParserDesc() {}

int ObBasicEnglishFTParserDesc::segment(
    ObFTParserParam *param,
    ObITokenIterator *&iter) const
{
  int ret = OB_SUCCESS;
  ObBEngFTParser *parser = nullptr;
  if (OB_ISNULL(param) || OB_ISNULL(param->fulltext_) || OB_UNLIKELY(!param->is_valid())) {
    ret = OB_INVALID_ARGUMENT;
  } else if (OB_ISNULL(parser = OB_NEWx(ObBEngFTParser, param->allocator_, *(param->allocator_)))) {
    ret = OB_ALLOCATE_MEMORY_FAILED;
  } else if (OB_FAIL(parser->init(param))) {
  } else {
    iter = parser;
  }

  if (OB_FAIL(ret)) {
    OB_DELETEx(ObBEngFTParser, param->allocator_, parser);
  }

  return ret;
}

void ObBasicEnglishFTParserDesc::free_token_iter(
    ObFTParserParam *param,
    ObITokenIterator *&iter) const
{
  if (OB_NOT_NULL(iter)) {
    abort_unless(nullptr != param);
    abort_unless(nullptr != param->allocator_);
    iter->~ObITokenIterator();
    param->allocator_->free(iter);
  }
}

int ObBasicEnglishFTParserDesc::get_add_word_flag(ObAddWordFlag &flag) const
{
  int ret = OB_SUCCESS;
  flag.set_min_max_word();
  flag.set_stop_word();
  flag.set_groupby_word();
  return ret;
}

